/* Declare printf directly so the program does not depend on a configured
    IntelliSense include path for stdio.h. */
extern int printf(const char *format, ...);


int main()
{
    int i, j, count;

    for(i = 2; i <= 1000; i++)
    {
        count = 0;

        for(j=1; j <= i; j++)
        {
            if(i % j == 0)
            {
                count++;

            }
        }






























































































































































































































        

        if(count == 2)
        {
            printf("%d ", i);
        }

    }
    return 0;
}